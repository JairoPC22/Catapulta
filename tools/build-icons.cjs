// Build only the Lucide icons used by the page from the checked-in vendor bundle.
// Run: node tools/build-icons.cjs
const fs = require('node:fs');
const path = require('node:path');
const vm = require('node:vm');
const root = path.resolve(__dirname, '..');
const source = fs.readFileSync(path.join(root, 'lucide.min.js'), 'utf8');
const sandbox = {};
vm.createContext(sandbox);
vm.runInContext(source, sandbox);
const pages = ['index.html', 'privacy.html', 'terms.html', 'cookies.html', '404.html', 'error.html', 'offline.html', 'catalogo.html'];
const names = new Set();
for (const page of pages) {
  const html = fs.readFileSync(path.join(root, page), 'utf8');
  for (const match of html.matchAll(/data-lucide="([^"]+)"/g)) names.add(match[1]);
}
names.add('alert-circle');
const selected = {};
for (const name of names) {
  const key = name.replace(/(^|-)(\w)/g, (_, dash, char) => char.toUpperCase());
  const icon = sandbox.lucide.icons[key];
  if (!icon) throw new Error(`Missing Lucide icon: ${name}`);
  selected[name] = icon;
}
const output = `${source.slice(0, source.indexOf('*/') + 2)}
// Generated by tools/build-icons.cjs. SVG paths are unchanged Lucide v0.469.0 data.
(() => {
  const icons = ${JSON.stringify(selected)};
  const element = ([tag, attributes, children = []]) => {
    const node = document.createElementNS('http://www.w3.org/2000/svg', tag);
    Object.entries(attributes).forEach(([key, value]) => node.setAttribute(key, value));
    children.forEach(child => node.append(element(child)));
    return node;
  };
  window.lucide = { createIcons() {
    document.querySelectorAll('i[data-lucide]').forEach(placeholder => {
      const name = placeholder.dataset.lucide;
      if (!icons[name]) return;
      const svg = element(icons[name]);
      for (const attribute of placeholder.attributes) svg.setAttribute(attribute.name, attribute.value);
      svg.classList.add('lucide', 'lucide-' + name);
      svg.setAttribute('focusable', 'false');
      placeholder.replaceWith(svg);
    });
  } };
})();
`;
fs.mkdirSync(path.join(root, 'assets/js'), { recursive: true });
fs.writeFileSync(path.join(root, 'assets/js/icons.js'), output);
console.log(`${names.size} icons; ${Buffer.byteLength(output)} bytes (vendor bundle: ${Buffer.byteLength(source)} bytes).`);
// Replace an 820 KB icon font with the eight SVG masks used by the terminal.
const terminal = { 'credit-card': 'CreditCard', wifi: 'Wifi', 'arrows-right-left': 'ArrowRightLeft', 'circle-check': 'CircleCheck', check: 'Check', rotate: 'RotateCcw', bolt: 'Zap', 'alert-triangle': 'TriangleAlert' };
const serialize = ([tag, attrs, children = []]) => `<${tag} ${Object.entries(attrs).map(([key, value]) => `${key}="${value}"`).join(' ')}>${children.map(serialize).join('')}</${tag}>`;
let css = '/* Lucide v0.469.0 SVG paths, ISC license. Generated by tools/build-icons.cjs. */\n.ti{display:inline-flex;width:1em;height:1em;vertical-align:-.125em;flex-shrink:0}.ti::before{content:"";display:block;width:1em;height:1em;background:currentColor;-webkit-mask:var(--terminal-icon) center/contain no-repeat;mask:var(--terminal-icon) center/contain no-repeat}\n';
for (const [alias, key] of Object.entries(terminal)) {
  const definition = sandbox.lucide.icons[key];
  if (!definition) throw new Error(`Missing terminal icon: ${key}`);
  css += `.ti-${alias}{--terminal-icon:url("data:image/svg+xml,${encodeURIComponent(serialize(definition))}")}\n`;
}
fs.mkdirSync(path.join(root, 'assets/css'), { recursive: true });
fs.writeFileSync(path.join(root, 'assets/css/terminal-icons.css'), css);
console.log(`Terminal SVG masks: ${Buffer.byteLength(css)} bytes.`);
